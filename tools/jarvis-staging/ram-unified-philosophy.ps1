# ============================================================================
# DISPLAY PHILOSOPHY
# ============================================================================

function Show-UnifiedPhilosophy {
    Write-Host ""
    Write-Host $UnifiedPhilosophy.Vision -ForegroundColor Magenta
    Write-Host ""

    Write-Host "THE FIVE PILLARS:" -ForegroundColor Cyan
    Write-Host "═" * 70 -ForegroundColor Cyan
    Write-Host ""

    foreach ($truth in $UnifiedPhilosophy.CoreTruths) {
        Write-Host "🌟 $($truth.Thai)" -ForegroundColor Yellow
        Write-Host "   ($($truth.English))" -ForegroundColor Gray
        Write-Host ""
        Write-Host "   Action: $($truth.Action)" -ForegroundColor Green
        Write-Host "   Meaning: $($truth.Meaning)" -ForegroundColor White
        Write-Host "   Poetry: '$($truth.Poetry)'" -ForegroundColor Magenta
        Write-Host ""
    }

    Write-Host $UnifiedPhilosophy.TheSacredDance -ForegroundColor Cyan
    Write-Host ""

    Write-Host "POETIC ESSENCE:" -ForegroundColor Magenta
    Write-Host "═" * 70 -ForegroundColor Magenta
    Write-Host ""
    foreach ($line in $UnifiedPhilosophy.PoetryOfRAM) {
        if ([string]::IsNullOrWhiteSpace($line)) {
            Write-Host ""
        } else {
            Write-Host "  $line" -ForegroundColor Yellow
        }
    }

    Write-Host ""
    Write-Host $UnifiedPhilosophy.TheFinalTruth -ForegroundColor Green
}

